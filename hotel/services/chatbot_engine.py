def _date(raw, label):
    try:
        return date.fromisoformat(str(raw))
    except (ValueError, TypeError) as exc:
        raise ValueError(f'{label} phải có định dạng YYYY-MM-DD.') from exc


def _count(raw, default=1):
    try:
        n = int(str(raw or default))
    except (TypeError, ValueError) as exc:
        raise ValueError('Số khách phải là số nguyên.') from exc
    if not 1 <= n <= 30:
        raise ValueError('Số khách cần trong khoảng 1 đến 30.')
    return n


def _vnd(raw):
    return f'{Decimal(str(raw)):,.0f}đ'


def _dates(args, context):
    old = context.get('quote') or context.get('search') or {}
    start = _date(args.get('checkin') or old.get('checkin'), 'Ngày nhận phòng')
    end = _date(args.get('checkout') or old.get('checkout'), 'Ngày trả phòng')
    business.dates_in_order(start, end)
    return start, end


def _room(db, key):
    key = str(key or '').strip()
    if not key:
        raise ValueError('Bạn muốn chọn phòng số mấy? Ví dụ: phòng 201.')
    room = db.scalar(select(Room).options(joinedload(Room.room_type)).where(Room.number == key))
    if room is None and key.isdigit():
        room = db.scalar(select(Room).options(joinedload(Room.room_type)).where(Room.id == int(key)))
    if room is None:
        raise ValueError('Không tìm thấy phòng này. Bạn hãy tìm phòng trống trước.')
    return room


def _booking_by_code(db, code):
    code = str(code or '').strip().upper()
    if not code:
        raise ValueError('Vui lòng cung cấp mã đặt phòng, ví dụ BK-XXXXXXXXXX.')
    booking = db.scalar(select(Booking).options(joinedload(Booking.customer),
                     joinedload(Booking.room), joinedload(Booking.invoice))
                     .where(Booking.code == code))
    if booking is None:
        raise ValueError('Không tìm thấy mã đặt phòng này.')
    return booking


def _status(booking):
    return {'pending': 'Chờ xác nhận', 'confirmed': 'Đã xác nhận', 'checked_in': 'Đã nhận phòng',
            'checked_out': 'Đã trả phòng', 'cancelled': 'Đã hủy'}.get(booking.status, booking.status)


def _range(args, default_days=30):
    today = date.today()
    end = _date(args.get('date_to') or today.isoformat(), 'Ngày kết thúc')
    start = _date(args.get('date_from') or (end-timedelta(days=default_days-1)).isoformat(),
                  'Ngày bắt đầu')
    if start > end or (end-start).days > 366:
        raise ValueError('Khoảng ngày thống kê không hợp lệ (tối đa 366 ngày).')
    return start, end


def execute(db, role, user_id, action, args, context):
    """Return (message, context_changes, optional_booking_request).

    `optional_booking_request` is *not* executed here; a separate human
    confirmation and a canonical controller.book() call are mandatory.
    """
    if role not in ROLE_ACTIONS or action not in ROLE_ACTIONS[role]:
        raise PermissionError('Bạn không được phép sử dụng công cụ này.')
    if action == 'reply':
        return 'Bạn có thể hỏi tôi về phòng, giá, dịch vụ và đặt phòng. Bạn cần hỗ trợ gì?', {}, None
    if action == 'hotel_info':
        fields = {
            'hotel_name': 'Tên khách sạn',
            'hotel_address': 'Địa chỉ',
            'hotel_phone': 'Số điện thoại',
            'checkin_time': 'Giờ nhận phòng',
            'checkout_time': 'Giờ trả phòng',
        }
        rows = db.scalars(select(SystemSetting).where(SystemSetting.key.in_(fields))).all()
        found = {item.key: item.value for item in rows if item.value}
        detail = '\n'.join(f'• {label}: {found[key]}' for key, label in fields.items() if key in found)
        return ('Thông tin khách sạn đang cấu hình trong MySQL:\n' + detail +
                '\nChính sách đặt cọc/hủy phòng chưa được cấu hình thành dữ liệu tra cứu; '
                'vui lòng liên hệ lễ tân để xác nhận điều khoản.'), {}, None
